"""
auth.py - Авторизация для запуска приложения
"""

import hashlib
import getpass

# Хэш пароля (по умолчанию "admin123")
# Для смены пароля используйте change_password.py
ПАРОЛЬ_ХЭШ = "93ed7071a1c6e55a1ccd873dedc710776895e8faa5ef2cd647d4ba09c30aca3d"

МАКС_ПОПЫТОК = 3  # Максимум попыток ввода

def проверить_пароль(ввод: str) -> bool:
    """Проверяет введенный пароль по SHA-256 хэшу"""
    хэш_ввода = hashlib.sha256(ввод.encode()).hexdigest()
    return хэш_ввода == ПАРОЛЬ_ХЭШ

def запрос_пароля():
    """Запрашивает пароль у пользователя с ограничением попыток"""
    попытка = 0
    while попытка < МАКС_ПОПЫТОК:
        ввод = getpass.getpass("Введите пароль для запуска приложения: ")
        if проверить_пароль(ввод):
            print("✅ Доступ разрешен.\n")
            return True
        else:
            попытка += 1
            print(f"❌ Неверный пароль. Осталось попыток: {МАКС_ПОПЫТОК - попытка}")
    print("❌ Превышено количество попыток. Выход.")
    return False

if __name__ == "__main__":
    # Пример использования
    if not запрос_пароля():
        exit(1)