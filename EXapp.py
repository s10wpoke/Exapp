    def настроить_скролл_мышью(self):
        """Добавляет поддержку колесика мыши для всех Canvas"""
        def on_mousewheel(event):
            # Находим все виджеты Canvas в окне
            widgets = self.root.winfo_children()
            for widget in widgets:
                if isinstance(widget, tk.Canvas):
                    # Проверяем, находится ли курсор над Canvas
                    x, y = widget.winfo_pointerxy()
                    wx, wy = widget.winfo_rootx(), widget.winfo_rooty()
                    ww, wh = widget.winfo_width(), widget.winfo_height()
                    
                    if wx <= x <= wx + ww and wy <= y <= wy + wh:
                        widget.yview_scroll(int(-1*(event.delta/120)), "units")
                        break
        
        # Привязываем колесико мыши к окну
        self.root.bind("<MouseWheel>", on_mousewheel)
        self.root.bind("<Button-4>", lambda e: on_mousewheel(type('Event', (), {'delta': 120})()))
        self.root.bind("<Button-5>", lambda e: on_mousewheel(type('Event', (), {'delta': -120})()))
    
