    def обновить_статистику(self):
        """Обновляет статистику на вкладке создания"""
        if not self.помещения:
            self.label_статистика.config(text="❌ Нет данные для создания ведомости!")
            self.text_предпросмотр.delete(1.0, tk.END)
            self.text_предпросмотр.insert(1.0, "Добавьте помещения на вкладке 'Добавить помещение'")
            self.label_инфо.config(text="Заголовок не настроен. Перейдите во вкладку 'Настройки'.")
            return
        
        # Обновляем заголовок
        номер = self.номер_дела.get().strip()
        адрес = self.адрес.get().strip()
        цена_иска = self.цена_иска.get().strip()
        if номер or адрес:
            инфо_текст = f"{номер} {адрес}".strip()
            if цена_иска:
                инфо_текст += f" (Цена иска: {цена_иска} руб.)"
            self.label_инфо.config(text=инфо_текст if инфо_текст else "Заголовок не настроен")
            # Сохраняем настройки в генератор
            self.генератор.установить_заголовок(номер, адрес)
        
        # Устанавливаем цену иска
        if цена_иска:
            self.генератор.установить_цену_иска(цена_иска)
        
        # Устанавливаем откосы
        откос_окна = self.откос_окна.get().strip()
        откос_двери = self.откос_двери.get().strip()
        if откос_окна or откос_двери:
            self.генератор.установить_откосы(откос_окна, откос_двери)
        
        # Рассчитываем общую площадь
        общая_площадь = 0
        for пом in self.помещения:
            расчет = self.генератор.рассчитать_помещение(пом)
            общая_площадь += расчет["площадь_пола"]
        
        текст = (f"✅ Готово к созданию ведомости:\n"
                f"• Помещений: {len(self.помещения)}\n"
                f"• Общая площадь: {общая_площадь:.2f} м²\n"
                f"• Дверей и проемов: {sum(len(п.get('двери', [])) for п in self.помещения)}\n"
                f"• Окон: {sum(len(п.get('окна', [])) for п in self.помещения)}")
        
        self.label_статистика.config(text=текст)
    
    def показать_предпросмотр(self):
        """Показывает предпросмотр ведомости"""
        if not self.помещения:
            messagebox.showerror("Ошибка", "Нет данные для предпросмотра!")
            return
        
