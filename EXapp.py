def защита_паролем():
    """GUI-версия защиты паролем для EXE"""
    import tkinter as tk
    from tkinter import ttk, messagebox
    
    class ОкноПароля:
        def __init__(self):
            self.корень = tk.Tk()
            self.корень.title("🔐 АВТОРИЗАЦИЯ")
            self.корень.geometry("450x320")
            self.корень.resizable(False, False)
            self.корень.configure(bg="#f0f0f0")
            
            # Центрируем окно
            self.центрировать_окно()
            
            # Переменные
            self.попытки = 3
            self.успешно = False
            
            # Создаем элементы
            self.создать_виджеты()
            
            # Фокус на поле ввода
            self.поле_пароль.focus()
            
            # Обработчики клавиш
            self.корень.bind('<Return>', lambda e: self.проверить_пароль())
            self.корень.bind('<Escape>', lambda e: self.отмена())
            
            # Защита от закрытия крестиком
            self.корень.protocol("WM_DELETE_WINDOW", self.отмена)
        
        def центрировать_окно(self):
            self.корень.update_idletasks()
            width = self.корень.winfo_width()
            height = self.корень.winfo_height()
            x = (self.корень.winfo_screenwidth() // 2) - (width // 2)
            y = (self.корень.winfo_screenheight() // 2) - (height // 2)
            self.корень.geometry(f'{width}x{height}+{x}+{y}')
        
        def создать_виджеты(self):
            # Основной фрейм
            основной_фрейм = ttk.Frame(self.корень, padding=25)
            основной_фрейм.pack(fill="both", expand=True)
            
            # Заголовок
            заголовок = ttk.Label(
                основной_фрейм,
                text="ГЕНЕРАТОР ВЕДОМОСТЕЙ ДЕФЕКТОВ",
                font=("Arial", 16, "bold"),
                foreground="#2c3e50"
            )
            заголовок.pack(pady=(0, 10))
            
            подзаголовок = ttk.Label(
                основной_фрейм,
                text="Требуется авторизация для доступа к программе",
                font=("Arial", 10),
                foreground="#7f8c8d"
            )
            подзаголовок.pack(pady=(0, 25))
            
            # Фрейм для пароля
            фрейм_пароль = ttk.Frame(основной_фрейм)
            фрейм_пароль.pack(pady=(0, 15))
            
