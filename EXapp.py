    def удалить_из_таблицы(self, tree, список):
        """Удаляет выбранный элемент из таблицы и списка"""
        selected = tree.selection()
        if not selected:
            return
        
        for item in selected:
            idx = int(tree.item(item, "values")[0]) - 1
            if 0 <= idx < len(список):
                del список[idx]
            tree.delete(item)
        
        # Обновляем номера
        self.обновить_номера_таблицы(tree)
    
    def обновить_номера_таблицы(self, tree):
        """Обновляет номера в таблице после удаления"""
        items = tree.get_children()
        for i, item in enumerate(items, 1):
            values = list(tree.item(item, "values"))
            values[0] = str(i)
            tree.item(item, values=values)
    
