    def обновить_список(self):
        """Обновляет список помещений в таблице"""
        # Очищаем таблицу
        for item in self.tree_помещения.get_children():
            self.tree_помещения.delete(item)
        
        # Заполняем заново
        for i, пом in enumerate(self.помещения, 1):
            дефекты_текст = ", ".join([d.replace("_", " ").title() for d in пом.get("дефекты", [])])
            
            self.tree_помещения.insert("", "end", values=(
                i,
                пом["название"],
                f"{пом['длина']:.2f}",
                f"{пом['ширина']:.2f}",
                f"{пом['высота']:.2f}",
                len(пом.get("двери", [])),
                len(пом.get("окна", [])),
                дефекты_текст[:100] + "..." if len(дефекты_текст) > 100 else дефекты_текст,
                len(пом.get("отклонения_пола", [])),
                len(пом.get("отклонения_стены", []))
            ))
        
        self.status_bar.config(text=f"Добавлено помещений: {len(self.помещения)}")
    
    def удалить_помещение_из_списка(self):
        """Удаляет выбранное помещение"""
        selected = self.tree_помещения.selection()
        if not selected:
            messagebox.showwarning("Внимание", "Выберите помещение для удаления!")
            return
        
        for item in selected:
            idx = int(self.tree_помещения.item(item, "values")[0]) - 1
            if 0 <= idx < len(self.помещения):
                del self.помещения[idx]
            self.tree_помещения.delete(item)
        
        self.обновить_список()
        messagebox.showinfo("Успех", "Помещение удалено!")
    
    def очистить_все_помещения(self):
        """Удаляет все помещения"""
        if not self.помещения:
            return
        
        if messagebox.askyesno("Подтверждение", "Удалить ВСЕ помещения?"):
            self.помещения.clear()
            self.обновить_список()
            messagebox.showinfo("Успех", "Все помещения удалены!")
    
    def экспорт_в_json(self):
        """Экспортирует все помещения в JSON файл"""
