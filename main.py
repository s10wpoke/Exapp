"""
main.py - Точка входа приложения
"""

from auth import проверить_пароль
from config import получить_настройки
from generator import ГенераторВедомости
from excel_export import экспорт_в_excel
from gui import запустить_gui


def main():
    настройки = получить_настройки()

    # ------------------------------
    # Проверка пароля
    # ------------------------------
    успешный_вход = False
    попытки = 0
    while попытки < настройки['макс_попыток']:
        пароль = input("Введите пароль для запуска приложения: ")
        if проверить_пароль(пароль):
            успешный_вход = True
            break
        else:
            попытки += 1
            print(f"❌ Неверный пароль. Попытка {попытки}/{настройки['макс_попыток']}")

    if not успешный_вход:
        print("🔒 Превышено количество попыток. Выход.")
        return

    print("✅ Доступ разрешен!")

    # ------------------------------
    # Создаем генератор ведомости
    # ------------------------------
    генератор = ГенераторВедомости()

    # Если запускаем GUI
    запустить_gui(генератор)

    # ------------------------------
    # После закрытия GUI можно экспортировать в Excel
    # ------------------------------
    сохранить = input("Сохранить ведомость в Excel? (y/n): ").lower()
    if сохранить == 'y':
        путь = input("Укажите путь для сохранения файла (Enter для использования пути по умолчанию): ")
        if путь.strip() == "":
            путь = настройки['путь_сохранения']
        экспорт_в_excel(генератор, путь)
        print(f"✅ Файл сохранен в {путь if путь else 'текущей папке'}")

    print("Программа завершена.")


if __name__ == "__main__":
    main()