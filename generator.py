# core/generator.py

from works_data import РАБОТЫ


# ==========================
# Безопасный расчёт формулы
# ==========================

def рассчитать_формулу(формула: str, параметры: dict) -> float:
    """
    Вычисляет формулу на основе переданных параметров.
    """
    if not формула:
        return 1

    try:
        return round(eval(формула, {}, параметры), 2)
    except Exception as e:
        print(f"Ошибка расчёта формулы: {e}")
        return 0


# ==========================
# Создание строки работы
# ==========================

def создать_работу(код: str, параметры: dict) -> dict:
    """
    Создаёт одну строку работы для Excel.
    """

    if код not in РАБОТЫ:
        raise ValueError(f"Код работы '{код}' не найден в базе")

    данные = РАБОТЫ[код]

    название = данные["название"]

    # 🔥 Добавляем размер только для демонтажа напольной плитки
    if код == "демонтаж_напольной_плитки":
        размер = параметры.get("размер_плитки")
        if размер:
            название += f" ({размер})"

    количество = рассчитать_формулу(
        данные["формула"],
        параметры
    )

    return {
        "раздел": данные["раздел"],
        "наименование": название,
        "единица": данные["единица"],
        "количество": количество
    }


# ==========================
# Генерация списка работ
# ==========================

def сгенерировать_работы(коды: list, параметры: dict) -> list:
    """
    Генерирует список работ по выбранным кодам.
    """

    результат = []

    for код in коды:
        строка = создать_работу(код, параметры)

        # Не добавляем нулевые позиции
        if строка["количество"] > 0:
            результат.append(строка)

    return результат