# generator.py
from works_data import РаботыБаза

class ГенераторВедомости:
    def __init__(self, размер_плитки="60x60"):
        self.база = РаботыБаза()
        self.размер_плитки = размер_плитки
        self.ведомость = []

    def создать_ведомость(self, выбранные_работы=None):
        """
        Создает ведомость для выбранных работ.
        Если выбранные_работы = None, берет все работы из базы.
        """
        работы = self.база.получить_работы()

        for ключ, секция in sorted(работы.items(), key=lambda x: x[1]["порядок"]):
            for работа in секция["работы"]:
                вид = работа["вид"]

                # Подставляем размер плитки для демонтаж/монтаж плитки
                if "размер" in работа:
                    вид = вид.format(размер=self.размер_плитки)

                # Фильтруем по выбранным работам, если нужно
                if выбранные_работы and ключ not in выбранные_работы:
                    continue

                self.ведомость.append({
                    "раздел": секция["раздел"],
                    "вид": вид,
                    "формула": работа.get("формула", ""),
                    "ед": работа.get("ед", "")
                })

        return self.ведомость

    def очистить_ведомость(self):
        """Очищает текущую ведомость"""
        self.ведомость = []