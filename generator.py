# core/generator.py

from core.works_data import РАБОТЫ


class ГенераторВедомости:

    def __init__(self):
        self.база = РАБОТЫ

    # ===============================
    # ПУБЛИЧНЫЙ МЕТОД
    # ===============================

    def создать(self, помещения: list) -> list:
        результат = []
        номер = 1

        for помещение in помещения:

            результат.append({
                "тип": "раздел",
                "название": помещение["название"]
            })

            for работа in помещение.get("работы", []):

                код = работа["код"]

                if код not in self.база:
                    continue

                данные = self.база[код]

                объем = self._рассчитать(
                    данные,
                    помещение.get("параметры", {}),
                    работа.get("параметры", {})
                )

                результат.append({
                    "тип": "работа",
                    "номер": номер,
                    "название": данные["название"],
                    "объем": round(объем, 2),
                    "ед": данные.get("единица", ""),
                    "раздел": данные.get("раздел", "")
                })

                номер += 1

        return результат

    # ===============================
    # ПРИВАТНЫЙ РАСЧЕТ
    # ===============================

    def _рассчитать(self, данные, параметры_помещения, параметры_работы):

        формула = данные.get("формула")

        if not формула:
            return 1

        # объединяем параметры
        контекст = {}
        контекст.update(параметры_помещения)
        контекст.update(параметры_работы)

        try:
            return eval(формула, {}, контекст)
        except Exception:
            return 0